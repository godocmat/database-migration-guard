def fixture_args(cluster, test_binary, major, scenario):
    args = [
        test_binary, "history::tests::native_history", "--ignored", "--exact", "--nocapture"
    ]
    settings = {
        "DMG_HISTORY_TEST_MAJOR": str(major),
        "DMG_HISTORY_TEST_CASE": scenario,
        "DMG_TEST_POSTGRES_PORT": str(cluster.port),
        "DMG_TEST_POSTGRES_CA": str(cluster.scratch / "ca.crt"),
        "DMG_TEST_POSTGRES_PASSWORD": cluster.password,
    }
    return args, settings


def check_output(cluster, scenario, code, output):
    require(cluster.password not in output, "history reader exposed a protected fixture value")
    print(f"{scenario}\n{output}", end="")
    require(code == 0 and "1 passed" in output, f"history assertion {scenario} failed")


def check(cluster, test_binary, major, scenario):
    args, settings = fixture_args(cluster, test_binary, major, scenario)
    result = cluster.run(*args, check=False, extra_env=settings)
    check_output(cluster, scenario, result.returncode, result.stdout + result.stderr)


def wait_for_relation_lock(cluster, oid, *, granted):
    lock = "AccessExclusiveLock" if granted else "AccessShareLock"
    owner = "" if granted else "AND a.application_name = 'dmg-inspect'"
    sql = f"""
SELECT 1 FROM pg_catalog.pg_locks l
JOIN pg_catalog.pg_stat_activity a ON a.pid = l.pid
WHERE l.relation = {oid} AND l.mode = '{lock}' AND l.granted = {str(granted).lower()}
  AND a.datname = current_database() {owner};
"""
    deadline = time.monotonic() + 2
    while time.monotonic() < deadline:
        if cluster.psql(sql).stdout.strip() == "1":
            return
        time.sleep(0.02)
    raise RuntimeError(f"fixture did not observe {lock} with granted={granted}")


@contextmanager
def relation_transaction(cluster, oid, sql):
    with subprocess.Popen(
        cluster.psql_args(ADMIN), cwd=cluster.scratch, env=cluster.env, text=True,
        stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    ) as process:
        try:
            process.stdin.write("BEGIN;\n" + sql + "\n")
            process.stdin.flush()
            wait_for_relation_lock(cluster, oid, granted=True)
            yield process
        finally:
            if process.stdin and not process.stdin.closed:
                _, errors = process.communicate("ROLLBACK;\n", timeout=5)
                require(process.returncode == 0, "fixture rollback failed\n" + errors)


def check_replacement(cluster, test_binary, major, oid):
    statements = f"""
ALTER TABLE {QUOTED} RENAME TO history_before_replacement;
CREATE TABLE {QUOTED} {SQLX_COLUMNS};
GRANT SELECT (version, success, checksum) ON {QUOTED} TO dmg_catalog_scope;
"""
    args, settings = fixture_args(cluster, test_binary, major, "replacement")
    with relation_transaction(cluster, oid, statements) as locker, subprocess.Popen(
        args, cwd=cluster.scratch, env={**cluster.env, **settings},
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
    ) as reader:
        try:
            wait_for_relation_lock(cluster, oid, granted=False)
            _, errors = locker.communicate("COMMIT;\n", timeout=5)
            require(locker.returncode == 0, "fixture replacement failed\n" + errors)
            output, _ = reader.communicate(timeout=8)
            check_output(cluster, "replacement", reader.returncode, output)
        finally:
            if reader.poll() is None:
                reader.kill()
                reader.communicate(timeout=5)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pg-bin", required=True, type=Path)
    parser.add_argument("--test-binary", required=True, type=Path)
    args = parser.parse_args()
    pg_bin = args.pg_bin.resolve(strict=True)
    test_binary = args.test_binary.resolve(strict=True)
    with tempfile.TemporaryDirectory(prefix="dmg-history-api-") as directory:
        cluster = Cluster(pg_bin, Path(directory), tls=True)
        version = cluster.run(pg_bin / "postgres", "--version").stdout.strip()
        match = re.search(r"\b(15|16|17|18)\.\d+$", version)
        require(match, "expected PostgreSQL 15 through 18 fixture binaries")
        major = int(match.group(1))
        with cluster.running():
            cluster.psql(SETUP)
            for query in (
                f"SELECT description FROM {QUOTED}",
                f"SELECT version FROM {QUOTED} LIMIT 1",
                "SELECT statements FROM supabase_migrations.schema_migrations",
            ):
                state, _ = cluster.failed_read(query)
                expected = "00000" if "LIMIT 1" in query else "42501"
                require(state == expected, f"unexpected history grant SQLSTATE {state}")
            check(cluster, test_binary, major, "ordinary")
            oid = int(cluster.psql(f"SELECT '{QUOTED}'::regclass::oid;").stdout)
            with relation_transaction(cluster, oid, f"LOCK TABLE ONLY {QUOTED} IN ACCESS EXCLUSIVE MODE;"):
                check(cluster, test_binary, major, "contention")
            check_replacement(cluster, test_binary, major, oid)
        print(version)
        print(f"postgres SHA-256 {sha256(pg_bin / 'postgres')}")


if __name__ == "__main__":
    main()
