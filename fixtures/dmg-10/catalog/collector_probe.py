
"""Check the production Rust catalog collector against a disposable TLS PostgreSQL cluster."""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import tempfile

from native_probe import READER, Cluster, require, sha256

SETUP = """
CREATE SCHEMA "catalog_Quoted";
GRANT USAGE ON SCHEMA "catalog_Quoted" TO dmg_catalog_scope;
CREATE SCHEMA catalog_simple;
GRANT USAGE ON SCHEMA catalog_simple TO dmg_catalog_scope;
CREATE TABLE catalog_simple.owned (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY);
CREATE TABLE "catalog_Quoted"."Table.With.Dot" ("column""quote" integer);
CREATE TYPE catalog_scope.status AS ENUM ('open', 'closed');
CREATE TABLE catalog_scope.details (
    "quoted key" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source text COLLATE "C",
    note varchar(12) DEFAULT 'fixture-text',
    labels text[],
    state catalog_scope.status DEFAULT 'open',
    trimmed text GENERATED ALWAYS AS (trim(source)) STORED,
    dropped_marker text,
    checked boolean
);
ALTER TABLE catalog_scope.details DROP COLUMN dropped_marker;
CREATE INDEX details_lookup ON catalog_scope.details ((lower(source)), "quoted key")
    INCLUDE (note) WHERE source IS NOT NULL;
CREATE UNIQUE INDEX details_note_idx ON catalog_scope.details (note) NULLS NOT DISTINCT;
ALTER TABLE catalog_hidden.hidden_table ADD PRIMARY KEY (id);
ALTER TABLE catalog_public.metadata_only ADD PRIMARY KEY (id);
CREATE SCHEMA catalog_outside;
CREATE TABLE catalog_outside.external_identity (id integer PRIMARY KEY);
CREATE TABLE catalog_scope.links (
    inside_id integer CONSTRAINT inside_fk REFERENCES catalog_scope.accounts
        DEFERRABLE INITIALLY DEFERRED,
    outside_id integer CONSTRAINT outside_fk REFERENCES catalog_outside.external_identity,
    later_id integer CONSTRAINT visible_fk REFERENCES catalog_public.metadata_only,
    private_id integer CONSTRAINT denied_fk REFERENCES catalog_hidden.hidden_table
);
CREATE TABLE catalog_hidden.outside_partition PARTITION OF catalog_scope.events
    FOR VALUES FROM (10) TO (20);
CREATE VIEW catalog_scope.ignored_view AS SELECT id FROM catalog_scope.accounts;
"""

def check(cluster, test_binary, major, scenario):
    result = cluster.run(
        test_binary, "catalog::tests::native_catalog", "--ignored", "--exact", "--nocapture",
        check=False,
        extra_env={
            "DMG_CATALOG_TEST_MAJOR": str(major),
            "DMG_CATALOG_TEST_CASE": scenario,
            "DMG_TEST_POSTGRES_PORT": str(cluster.port),
            "DMG_TEST_POSTGRES_CA": str(cluster.scratch / "ca.crt"),
            "DMG_TEST_POSTGRES_PASSWORD": cluster.password,
        },
    )
    output = result.stdout + result.stderr
    require(cluster.password not in output, "collector assertions exposed a protected fixture value")
    print(f"{scenario}\n{output}", end="")
    require(result.returncode == 0 and "1 passed" in output, f"collector assertion {scenario} failed")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pg-bin", required=True, type=Path)
    parser.add_argument("--test-binary", required=True, type=Path)
    args = parser.parse_args()
    pg_bin = args.pg_bin.resolve(strict=True)
    test_binary = args.test_binary.resolve(strict=True)
    with tempfile.TemporaryDirectory(prefix="dmg-catalog-api-") as directory:
        cluster = Cluster(pg_bin, Path(directory), tls=True)
        version = cluster.run(pg_bin / "postgres", "--version").stdout.strip()
        match = re.search(r"\b(15|16|17|18)\.\d+$", version)
        require(match, "expected PostgreSQL 15 through 18 fixture binaries")
        major = int(match.group(1))
        with cluster.running():
            cluster.psql(SETUP)
            if major == 18:
                cluster.psql("""
ALTER TABLE catalog_scope.details
    ADD COLUMN virtual_length integer GENERATED ALWAYS AS (length(source)) VIRTUAL,
    ADD CONSTRAINT virtual_positive CHECK (virtual_length > 0) NOT ENFORCED;
CREATE TABLE catalog_scope.ranges (key int4range, span int4range, PRIMARY KEY (key, span WITHOUT OVERLAPS));
""")
            cluster.psql("CREATE TABLE catalog_scope.long_definition (value text DEFAULT '" + "x" * 9000 + "');")
            app_read, _ = cluster.failed_read("SELECT id FROM catalog_scope.accounts")
            require(app_read == "42501", "fixture reader can access application rows")
            check(cluster, test_binary, major, "available")
            with cluster.hold_access_exclusive():
                for scenario in ("lock", "cancel", "deadline"):
                    check(cluster, test_binary, major, scenario)
            for name in ("pg_get_expr(pg_node_tree, oid, boolean)", "pg_get_indexdef(oid, integer, boolean)",
                         "pg_get_constraintdef(oid, boolean)", "pg_total_relation_size(regclass)"):
                cluster.psql(f"REVOKE EXECUTE ON FUNCTION pg_catalog.{name} FROM PUBLIC")
            check(cluster, test_binary, major, "denied")
            cluster.psql("REVOKE SELECT ON pg_catalog.pg_attribute FROM PUBLIC")
            check(cluster, test_binary, major, "projection-denied")

        print(version)
        print(f"postgres SHA-256 {sha256(pg_bin / 'postgres')}")


if __name__ == "__main__":
    main()
